score = 55
pass_mark = 50

if score >= pass_mark:
    print("Passed")
else:
    print("Failed")


##DIFFERENCE BETWEEN = AND ==
# = Is assignment. It stores a value in a variable: score = 55 means "put 55 into score."
# == is comparison. It asks a question: score == 55 means "is score equal to 55?" and gives TRUE/FALSE
